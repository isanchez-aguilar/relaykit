// Install the work contract, the generic roles and the generic skills into the
// GLOBAL configuration of Claude Code, Codex and Antigravity, so every agent in
// every folder works the same way. The sources live in this repo
// (docs/contract.md, agents/, skills/); the global copies are generated — edit
// the source and run this again.
//
//   relayrace sync            preview, then ask before writing
//   relayrace sync --check    exit 1 on drift (never writes)
//
// It only ever replaces files it generated itself (they carry GENERATED), and
// it refuses measured Codex instruction loads above the configured byte budget.
// It reports incomplete coverage when discovery cannot be evaluated. Projects
// come from Agent Desk and the known working directory.
//
// Dependency-free: Node 18+ built-ins only.

import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, renameSync, unlinkSync, rmdirSync, statSync, lstatSync, constants } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { codexConfigDir, loadConfig } from './lib/config.mjs';
import { configuredDocBudget, effectiveInstructions, measureProjects } from './lib/codex-budget.mjs';
import { confirm } from './lib/prompt.mjs';
import { isMain } from './lib/is-main.mjs';

export const KIT_DIR = dirname(fileURLToPath(import.meta.url));
export const CONTRACT_FILE = join(KIT_DIR, 'docs', 'contract.md');
export const GENERATED = 'GENERATED by relaykit sync — edit the source in the Relaykit repo (docs/contract.md, agents/, skills/), not this copy';
// Files written before the kit moved into its own repo (and before its rename) carry
// these older marks. They are still ours to replace, or the first sync after the move
// would refuse every one of them.
export const LEGACY_GENERATED = 'GENERATED by IA local/kit/sync.mjs';
export const LEGACY_GENERATED_AI_KIT = 'GENERATED by ai-kit sync';
export const GENERATED_HEADERS = [GENERATED,
  `${LEGACY_GENERATED} — edit the source in the notes, not this copy`,
  `${LEGACY_GENERATED_AI_KIT} — edit the source in the ai-kit repo`,
  `${LEGACY_GENERATED_AI_KIT} — edit the source in the ai-kit repo (docs/contract.md, agents/, skills/), not this copy`,
].flatMap(mark => [`<!-- ${mark} -->`, `# ${mark}`]);
export function isGenerated(text) {
  const normalized = text.replace(/\r\n/g, '\n');
  // Markdown metadata may precede the first body line; arbitrary prose may not.
  const body = normalized.replace(/^---\n[\s\S]*?\n---\n/, '');
  return GENERATED_HEADERS.includes(body.split('\n')[0]);
}
export const BLOCK_START = '<!-- RELAYKIT_CONTRACT_START -->';
export const BLOCK_END = '<!-- RELAYKIT_CONTRACT_END -->';
// The markers an earlier version wrote into global files; a block between them is migrated to the new ones.
const LEGACY_BLOCKS = [['<!-- ISAAC_CONTRACT_START -->', '<!-- ISAAC_CONTRACT_END -->']];
// Codex stops adding instruction files at project_doc_max_bytes (32 KiB by
// default). Keep a margin for a nested AGENTS.md or a small override.
export const CODEX_BUDGET = 32 * 1024 - 2048;

/** The contract body between the file's markers. */
export function extractContract(note) {
  const match = note.replace(/\r\n/g, '\n').match(/<!-- (?:contract:start|contrato:inicio) -->\n([\s\S]*?)\n<!-- (?:contract:end|contrato:fin) -->/);
  if (!match || !match[1].trim()) throw new Error('The contract file has no text between <!-- contract:start --> and <!-- contract:end -->.');
  return match[1].trim();
}

/** `text` with the managed block replaced, or appended when it is not there yet. */
export function upsertBlock(text, body) {
  const block = `${BLOCK_START}\n<!-- ${GENERATED} -->\n${body}\n${BLOCK_END}`;
  const normalized = text.replace(/\r\n/g, '\n');
  for (const [startMarker, endMarker] of [[BLOCK_START, BLOCK_END], ...LEGACY_BLOCKS]) {
    const start = normalized.indexOf(startMarker);
    const end = normalized.indexOf(endMarker);
    if (start === -1 && end === -1) continue;
    if (normalized.split(startMarker).length !== 2 || normalized.split(endMarker).length !== 2 || end <= start) {
      throw new Error('Found only one contract marker or duplicate/out-of-order markers; fix the file by hand.');
    }
    const owned = normalized.slice(start + startMarker.length, end);
    if (!owned.startsWith('\n') || !isGenerated(owned.slice(1))) throw new Error('Contract block was not generated by relayrace sync.');
    return normalized.slice(0, start) + block + normalized.slice(end + endMarker.length);
  }
  return `${normalized.trimEnd()}${normalized.trim() ? '\n\n' : ''}${block}\n`;
}

/** Frontmatter fields and body of an agent or skill Markdown source. */
export function parseSource(text, label) {
  const match = text.replace(/\r\n/g, '\n').match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`${label}: missing frontmatter.`);
  const fields = {};
  for (const line of match[1].split('\n')) {
    const field = line.match(/^(\w+):\s*(.*)$/);
    if (field) fields[field[1]] = field[2];
  }
  if (!fields.name || !fields.description) throw new Error(`${label}: name and description are required.`);
  return { fields, body: match[2].trim() };
}

/** The Claude copy: the source with the GENERATED marker as the body's first line. */
export function toClaudeFile(text) {
  const normalized = text.replace(/\r\n/g, '\n');
  const end = normalized.indexOf('\n---\n', 4) + 5;
  return `${normalized.slice(0, end)}<!-- ${GENERATED} -->\n${normalized.slice(end)}`;
}

/**
 * The Codex custom agent for a role. TOML basic strings would read a backslash
 * as an escape and `"""` would end the instructions early, so either is refused
 * rather than silently changing what Codex reads.
 */
export function toCodexToml(text, label) {
  const { fields, body } = parseSource(text, label);
  for (const [name, value] of [['description', fields.description], ['body', body]]) {
    if (value.includes('"""') || value.includes('\\')) throw new Error(`${label}: ${name} cannot contain """ or a backslash.`);
  }
  if (fields.description.includes('"')) throw new Error(`${label}: description cannot contain a double quote.`);
  const readOnly = /\b(Edit|Write)\b/.test(fields.disallowedTools || '');
  return [
    `# ${GENERATED}`,
    `name = "${fields.name}"`,
    `description = "${fields.description}"`,
    ...(fields.effort ? [`model_reasoning_effort = "${fields.effort}"`] : []),
    ...(readOnly ? ['sandbox_mode = "read-only"'] : []),
    `developer_instructions = """\n${body}\n"""`,
    '',
  ].join('\n');
}

/** Bytes Codex would load for the biggest known project, with this global file. */
export function codexLoad(globalText, projectSizes) {
  return Buffer.byteLength(globalText) + Math.max(0, ...projectSizes);
}

/** AGENTS.md sizes of the projects Agent Desk knows about (none when it is not configured). */
export function knownProjectSizes(agentDeskConfig, options) {
  return measureProjects(agentDeskConfig, options).sizes;
}

/** Every file sync owns, with the content it should have. */
export function plan({ home = homedir(), codexHome = codexConfigDir({ home }), kitDir = KIT_DIR, contractFile = CONTRACT_FILE } = {}) {
  const contract = extractContract(readFileSync(contractFile, 'utf8'));
  const read = path => (existsSync(path) ? readFileSync(path, 'utf8') : '');
  const files = [];
  for (const target of [join(home, '.claude/CLAUDE.md'), join(codexHome, 'AGENTS.md')]) {
    files.push({ path: target, content: upsertBlock(read(target), contract), managedBlock: true });
  }
  files.push({ path: join(home, '.gemini/antigravity-cli/rules/relaykit-contract.md'), content: `<!-- ${GENERATED} -->\n${contract}\n` });
  const agentsDir = join(kitDir, 'agents');
  for (const file of readdirSync(agentsDir).filter(f => f.endsWith('.md')).sort()) {
    const text = readFileSync(join(agentsDir, file), 'utf8');
    const { fields } = parseSource(text, `agents/${file}`);
    if (`${fields.name}.md` !== file) throw new Error(`agents/${file}: name must match the file name.`);
    if (/fable/i.test(fields.model || '')) throw new Error(`agents/${file}: a role may not run on Fable; the owner approves each Fable use.`);
    if (!fields.model || fields.model === 'inherit') throw new Error(`agents/${file}: pin an explicit model (haiku, sonnet or opus), never inherit.`);
    files.push({ path: join(home, '.claude/agents', file), content: toClaudeFile(text) });
    files.push({ path: join(codexHome, 'agents', `${fields.name}.toml`), content: toCodexToml(text, `agents/${file}`) });
  }
  const skillsDir = join(kitDir, 'skills');
  for (const name of readdirSync(skillsDir).sort()) {
    const source = join(skillsDir, name, 'SKILL.md');
    if (!existsSync(source)) continue;
    const text = readFileSync(source, 'utf8');
    if (parseSource(text, `skills/${name}`).fields.name !== name) throw new Error(`skills/${name}: name must match the folder.`);
    files.push({ path: join(home, '.claude/skills', name, 'SKILL.md'), content: toClaudeFile(text) });
  }
  return files;
}

/** Writes (or, with check, compares) every planned file. Returns the drifted paths. */
export function sync({ home = homedir(), codexHome = codexConfigDir({ home }), kitDir = KIT_DIR, contractFile = CONTRACT_FILE, check = false,
  agentDeskConfig, cwd, log = console.log, io = {}, now = () => new Date(), onPlan = () => {} } = {}) {
  const files = plan({ home, codexHome, kitDir, contractFile });
  const proposed = files.find(f => f.path === join(codexHome, 'AGENTS.md')).content;
  const coverage = measureProjects(agentDeskConfig, { cwd });
  const configured = configuredDocBudget(codexHome);
  coverage.incomplete.push(...configured.incomplete);
  let global = proposed;
  try {
    const effective = effectiveInstructions(codexHome);
    if (effective.path === join(codexHome, 'AGENTS.override.md')) global = effective.text;
  } catch { coverage.incomplete.push('global Codex instructions are unreadable'); }
  const load = codexLoad(global, coverage.sizes);
  // Keep the historic 2 KiB safety margin, including for a configured limit.
  const budget = Math.max(0, configured.limit - 2048);
  if (load > budget) throw new Error('Codex would load ' + load + ' bytes (budget ' + budget + '); shorten the contract or project instructions.');
  for (const reason of new Set(coverage.incomplete)) log('Codex coverage incomplete: ' + reason + '; no budget guarantee.');

  // Preflight the entire plan before backups, directories or replacements exist.
  const changes = [];
  for (const file of files) {
    let current = null;
    try {
      const info = lstatSync(file.path);
      if (!info.isFile() || info.isSymbolicLink()) throw new Error(file.path + ' is not a regular owned file.');
      current = readFileSync(file.path);
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current?.toString('utf8').replace(/\r\n/g, '\n') === file.content) continue;
    if (current !== null && !file.managedBlock && !isGenerated(current.toString('utf8'))) {
      throw new Error(file.path + ' exists and was not generated by relayrace sync; move it away or merge it by hand.');
    }
    for (let dir = dirname(file.path); ; dir = dirname(dir)) {
      try { if (!statSync(dir).isDirectory()) throw new Error(dir + ' is not a directory.'); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (dirname(dir) === dir) break;
    }
    changes.push({ ...file, current });
  }
  // Retire the old rule only after its replacement, and only with exact ownership.
  const legacy = join(home, '.gemini/antigravity-cli/rules/isaac-contract.md');
  const preserved = [];
  try {
    const info = lstatSync(legacy);
    const current = info.isFile() && !info.isSymbolicLink() ? readFileSync(legacy) : null;
    if (current !== null && isGenerated(current.toString('utf8'))) changes.push({ path: legacy, current, remove: true });
    else {
      preserved.push(legacy);
      log('preserved ' + legacy + ': not an owned generated file; review and remove it manually to clear drift.');
    }
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  onPlan({ changes: changes.length, preserved: preserved.length });
  if (!check && changes.length) applyTransaction(changes, { ...io, now });
  if (!check) for (const file of changes) log((file.remove ? 'removed ' : 'updated ') + file.path);
  log((check ? 'check' : 'sync') + ': ' + files.length + ' files, ' + changes.length + (check ? ' out of date' : ' changed') + '; ' + preserved.length + ' unresolved legacy files; Codex measured load ' + load + '/' + budget + ' bytes');
  return [...changes.map(file => file.path), ...preserved];
}

/** Roll back every replaced byte and remove newly created paths if any step fails. */
export function applyTransaction(changes, { write = writeFileSync, rename = renameSync, copy = copyFileSync, remove = unlinkSync, now = () => new Date() } = {}) {
  let timestamp = now().getTime();
  let stamp = new Date(timestamp).toISOString().replaceAll(':', '-');
  // A second run in the same millisecond must not replace the previous backup.
  while (changes.some(f => existsSync(f.path + '.bak-relaykit-' + stamp))) {
    stamp = new Date(++timestamp).toISOString().replaceAll(':', '-');
  }
  const id = randomUUID(), staged = [], replaced = [], backups = [], directories = [];
  const ensure = directory => {
    if (existsSync(directory)) return;
    ensure(dirname(directory));
    mkdirSync(directory); directories.push(directory);
  };
  try {
    for (const file of changes) {
      ensure(dirname(file.path));
      const temp = file.path + '.tmp-relaykit-' + id;
      staged.push(temp);
      file.mode = file.current === null ? 0o600 : statSync(file.path).mode;
      if (!file.remove) write(temp, file.content, { flag: 'wx', mode: file.mode });
      if (file.current !== null) {
        const backup = file.path + '.bak-relaykit-' + stamp;
        copy(file.path, backup, constants.COPYFILE_EXCL); backups.push(backup);
      }
    }
    for (let i = 0; i < changes.length; i++) {
      if (changes[i].remove) rename(changes[i].path, staged[i]);
      else rename(staged[i], changes[i].path);
      replaced.push(changes[i]);
    }
    for (const temp of staged) if (existsSync(temp)) remove(temp);
  } catch (failure) {
    const errors = [];
    for (const file of replaced.reverse()) {
      try {
        if (file.current === null) unlinkSync(file.path);
        else {
          const restore = file.path + '.restore-relaykit-' + id;
          staged.push(restore);
          writeFileSync(restore, file.current, { flag: 'wx', mode: file.mode });
          renameSync(restore, file.path);
        }
      } catch (error) { errors.push(error); }
    }
    for (const temp of staged) { try { if (existsSync(temp)) unlinkSync(temp); } catch (error) { errors.push(error); } }
    // Keep backups if recovery itself failed; the error explicitly reports that.
    if (!errors.length) for (const backup of backups) { try { unlinkSync(backup); } catch (error) { errors.push(error); } }
    for (const directory of directories.reverse()) { try { rmdirSync(directory); } catch (error) { if (error.code !== 'ENOTEMPTY') errors.push(error); } }
    if (errors.length) throw new AggregateError([failure, ...errors], 'Sync failed and restoration is incomplete; retain the timestamped backups.');
    throw failure;
  }
}

/** The CLI entry: `relayrace sync [--check]`. Resolves the machine's config, then syncs. */
export async function runSync(argv = [], { config = loadConfig(), log = console.log,
  interactive = Boolean(process.stdin.isTTY && process.stdout.isTTY), prompt = confirm, ...options } = {}) {
  const unknown = argv.filter(a => !['--check', '--yes'].includes(a));
  if (unknown.length) throw new Error(`unknown argument ${unknown[0]} (usage: sync [--check|--yes])`);
  const settings = { log, codexHome: config.values.codexHome, cwd: process.cwd(), agentDeskConfig: config.values.agentDesk,
    ...(config.values.contract ? { contractFile: config.values.contract } : {}), ...options };
  let count = 0;
  const drift = sync({ ...settings, check: true, onPlan: plan => { count = plan.changes; } });
  if (argv.includes('--check')) return drift.length ? 1 : 0;
  if (!argv.includes('--yes') && !interactive) {
    log('Non-interactive terminal: behaving like --check; use --yes to apply changes.');
    return drift.length ? 1 : 0;
  }
  if (!count) return drift.length ? 1 : 0;
  if (!argv.includes('--yes') && !await prompt(`Apply these ${count} changes? [y/N] `)) {
    log('No changes applied.');
    return drift.length ? 1 : 0;
  }
  sync({ ...settings, check: false });
  return 0;
}

if (isMain(import.meta.url)) {
  try {
    process.exitCode = await runSync(process.argv.slice(2));
  } catch (error) {
    console.error(`sync: ${error.message}`);
    process.exitCode = 2;
  }
}
