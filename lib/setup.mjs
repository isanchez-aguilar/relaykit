// Shared setup effects are injectable: tests never edit a real PATH or shell profile.
import { chmodSync, existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, resolve, win32, posix } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { confirm } from './prompt.mjs';
import { isMain } from './is-main.mjs';

const marker = 'Generated by Relaykit setup';
export const shellQuote = value => "'" + value.replaceAll("'", "'\\''") + "'";
const psQuote = value => "'" + value.replaceAll("'", "''") + "'";
const pathApi = platform => platform === 'win32' ? win32 : posix;

export function userBin({ platform = process.platform, env = process.env, home = homedir() } = {}) {
  const paths = pathApi(platform);
  return platform === 'win32' ? paths.join(env.LOCALAPPDATA || paths.join(home, 'AppData', 'Local'), 'Relaykit', 'bin') : paths.join(home, '.local', 'bin');
}

export function launcherFiles({ platform = process.platform, node, kitDir }) {
  if ([node, kitDir].some(value => /[\r\n\0]/.test(value))) throw new Error('Launcher paths cannot contain newlines or NUL.');
  const entry = pathApi(platform).join(kitDir, 'bin', 'relaykit.mjs');
  if (platform === 'win32') {
    const batch = value => value.replaceAll('%', '%%');
    return {
      'relaykit.cmd': `@echo off\r\nrem ${marker}\r\nsetlocal DisableDelayedExpansion\r\nfor /f "tokens=2 delims=:" %%c in ('"%SystemRoot%\\System32\\chcp.com"') do set "relaykit_codepage=%%c"\r\n"%SystemRoot%\\System32\\chcp.com" 65001 >nul\r\n"${batch(node)}" "${batch(entry)}" %*\r\nset "relaykit_status=%errorlevel%"\r\n"%SystemRoot%\\System32\\chcp.com" %relaykit_codepage% >nul\r\nexit /b %relaykit_status%\r\n`,
      // PowerShell prefers .ps1 over .cmd. Keep this optional companion off PATH
      // so the default command also works under Restricted execution policy.
      'powershell/relaykit.ps1': `\uFEFF# ${marker}\n& ${psQuote(node)} ${psQuote(entry)} @args\nexit $LASTEXITCODE\n`,
    };
  }
  return { relaykit: `#!/bin/sh\n# ${marker}\nexec ${shellQuote(node)} ${shellQuote(entry)} "$@"\n` };
}

export function pathContains(value, directory, platform = process.platform) {
  const paths = pathApi(platform);
  const normalize = item => {
    const normalized = paths.normalize(item.replace(/^"|"$/g, '')).replace(/[\\/]+$/, '');
    return platform === 'win32' ? normalized.toLowerCase() : normalized;
  };
  return (value || '').split(platform === 'win32' ? ';' : ':').some(item => item && normalize(item) === normalize(directory));
}

export function pathPlan({ platform = process.platform, env = process.env, home = homedir(), bin = userBin({ platform, env, home }), userPath = '', exists = existsSync, read = file => existsSync(file) ? readFileSync(file, 'utf8') : '' } = {}) {
  if (platform === 'win32') return pathContains(userPath, bin, platform) ? [] : [{ target: 'User PATH', value: userPath ? `${userPath.replace(/;$/, '')};${bin}` : bin, append: bin }];
  const paths = pathApi(platform);
  const shell = paths.basename(env.SHELL || '/bin/sh');
  const login = ['.bash_profile', '.bash_login', '.profile'].find(name => exists(paths.join(home, name))) || '.profile';
  const files = shell === 'zsh' ? ['.zprofile', '.zshrc'] : shell === 'fish' ? ['.config/fish/config.fish'] : [login, '.bashrc'];
  const block = shell === 'fish' ? `\n# ${marker}\nfish_add_path --path ${shellQuote(bin)}\n` : `\n# ${marker}\ncase ":$PATH:" in\n  *:${shellQuote(bin)}:*) ;;\n  *) export PATH=${shellQuote(bin)}:"$PATH" ;;\nesac\n`;
  return files.flatMap(name => {
    const target = paths.join(shell === 'zsh' ? env.ZDOTDIR || home : home, name), current = read(target);
    return current.replace(/\r\n/g, '\n').includes(block.trim()) ? [] : [{ target, value: current + block, append: block }];
  });
}

export function powershell(script, { run = spawnSync, input } = {}) {
  const utf8 = '[Console]::InputEncoding = New-Object System.Text.UTF8Encoding $false; [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding $false; ';
  // Absolute path: a bare name would be looked up in the current folder first on Windows.
  const exe = win32.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
  const result = run(exe, ['-NoProfile', '-NonInteractive', '-Command', utf8 + script], { encoding: 'utf8', input, windowsHide: true });
  if (result.error || result.status !== 0) throw new Error('Unable to read or update User PATH with PowerShell.');
  return String(result.stdout || '').trim();
}
export const readUserPath = () => JSON.parse(powershell("ConvertTo-Json -Compress -InputObject ([Environment]::GetEnvironmentVariable('Path', 'User'))") || 'null') || '';
export const writeUserPath = value => powershell("$value = [Console]::In.ReadToEnd(); [Environment]::SetEnvironmentVariable('Path', $value, 'User')", { input: value });

export async function setup({ platform = process.platform, env = process.env, home = homedir(), node = realpathSync(process.execPath),
  kitDir = resolve(dirname(fileURLToPath(import.meta.url)), '..'), yes = false, interactive = Boolean(process.stdin.isTTY && process.stdout.isTTY),
  prompt = confirm, log = console.log, getUserPath = readUserPath, setUserPath = writeUserPath, exists = existsSync,
  read = file => existsSync(file) ? readFileSync(file, 'utf8') : '',
  write = (file, text) => { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, text); }, chmod = chmodSync,
} = {}) {
  if (Number(process.versions.node.split('.')[0]) < 18) throw new Error('Node 18+ is required. Install Node from https://nodejs.org/ and run setup again.');
  const bin = userBin({ platform, env, home });
  log(`Node ${process.version}: ${node}`);
  log(`Relaykit checkout: ${kitDir}`);
  const files = Object.entries(launcherFiles({ platform, node, kitDir })).map(([name, text]) => ({ path: pathApi(platform).join(bin, name), text }));
  for (const file of files) {
    const existing = read(file.path);
    if (existing && !existing.includes(marker)) throw new Error(`Refusing to replace an unrelated launcher: ${file.path}`);
  }
  for (const file of files) {
    write(file.path, file.text);
    if (platform !== 'win32') chmod(file.path, 0o755);
    log(`Launcher: ${file.path}`);
  }
  const edits = pathPlan({ platform, env, home, bin, userPath: platform === 'win32' ? getUserPath() : '', read, exists });
  for (const edit of edits) log(`Append to ${edit.target}:\n${edit.append}`);
  if (edits.length) {
    const accepted = yes || (interactive && await prompt('Add Relaykit to your user PATH? [y/N] '));
    if (accepted) {
      for (const edit of edits) {
        if (platform === 'win32') setUserPath(edit.value);
        else write(edit.target, edit.value);
      }
      log('User PATH updated. Open a new terminal (restart the terminal app if it keeps the old PATH).');
    } else log('PATH unchanged. Run setup again and answer Y, or use --yes (-Yes in PowerShell).');
  } else log('User PATH is already configured.');
  log('Next command (in a new terminal): relaykit doctor');
  return { bin, edits };
}

if (isMain(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== '--yes')) throw new Error('usage: setup [--yes]');
    await setup({ yes: args.includes('--yes') });
  } catch (error) { console.error(`setup: ${error.message}`); process.exitCode = 1; }
}
