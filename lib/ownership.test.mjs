import { test } from 'node:test';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { hasBlock, hasMarkerLine } from './ownership.mjs';
import { HOOK_MARKER, LEGACY_HOOK_MARKERS, hookScript, manageHook } from './ci-local.mjs';
import { launcherFiles, pathPlan, setup } from './setup.mjs';

const MARKS = ['Generated by Relayrace setup', 'Generated by Relaykit setup'];

test('a mark counts only as a line of its own, behind at most a comment token', () => {
  for (const text of ['# Generated by Relayrace setup\nexec x', 'rem Generated by Relaykit setup\r\n@echo off', '\uFEFF# Generated by Relayrace setup\n',
    '#!/bin/sh\n   #   Generated by Relayrace setup   \nexec x', ':: Generated by Relayrace setup', 'Generated by Relayrace setup']) {
    assert.equal(hasMarkerLine(text, MARKS), true, JSON.stringify(text));
  }
  for (const text of ['# my own launcher, not Generated by Relayrace setup\n', 'echo "Generated by Relayrace setup"', '# Generated by Relayrace setup (edited by hand)',
    'x = "# Generated by Relayrace setup"', '# see: Generated by Relaykit setup', '']) {
    assert.equal(hasMarkerLine(text, MARKS), false, JSON.stringify(text));
  }
});

test('a block counts only as consecutive whole lines', () => {
  const block = '\n# Generated by Relayrace setup\ncase x in\nesac\n';
  assert.equal(hasBlock(`# keep\n${block}`, block), true);
  assert.equal(hasBlock(`# keep\r\n${block.replace(/\n/g, '\r\n')}`, block), true);
  assert.equal(hasBlock(`x # Generated by Relayrace setup\ncase x in\nesac\n`, block), false);
  assert.equal(hasBlock('# Generated by Relayrace setup\ncase y in\nesac\n', block), false);
});

test('setup: a custom launcher that mentions the mark in a comment is not overwritten; real and legacy ones are', async () => {
  const run = existing => setup({ platform: 'linux', home: '/fake', env: { SHELL: '/bin/bash' }, yes: true, interactive: false, node: '/n', kitDir: '/k',
    read: file => (file.endsWith('/relayrace') ? existing : ''), exists: () => false, write: () => {}, chmod: () => {}, log: () => {} });
  await assert.rejects(run('#!/bin/sh\n# I copied this from Generated by Relayrace setup\nexec mine\n'), /unrelated launcher/);
  await assert.rejects(run('#!/bin/sh\necho "Generated by Relayrace setup"\n'), /unrelated launcher/);
  await run(launcherFiles({ platform: 'linux', node: '/n', kitDir: '/k' }).relayrace);
  await run('#!/bin/sh\n# Generated by Relaykit setup\nexec node x\n');
  const windows = launcherFiles({ platform: 'win32', node: 'C:\\n\\node.exe', kitDir: 'C:\\Kit' });
  assert.equal(hasMarkerLine(windows['relayrace.cmd'], MARKS), true);
  assert.equal(hasMarkerLine(windows['powershell/relayrace.ps1'], MARKS), true);
});

test('setup: a shell profile that merely mentions the mark still gets the PATH block', () => {
  const env = { SHELL: '/bin/bash' };
  const edits = pathPlan({ platform: 'linux', home: '/h', env, exists: () => false, read: () => '# Generated by Relayrace setup is mentioned here\n' });
  assert.equal(edits.length, 2);
  const done = pathPlan({ platform: 'linux', home: '/h', env, exists: () => false, read: () => '' });
  const again = pathPlan({ platform: 'linux', home: '/h', env, exists: () => false, read: () => done[0].value });
  assert.deepEqual(again, []);
});

test('ci-local: a custom hook that mentions the mark in a comment is neither replaced nor removed; real and legacy hooks are ours', () => {
  const HOOK = resolve('/repo/.git/hooks/pre-push');
  const harness = existing => {
    const files = new Map([[HOOK, existing]]);
    return { files, options: { cwd: '/repo', node: 'n', cli: 'c', run: () => ({ status: 0, stdout: `${HOOK}\n` }), exists: file => files.has(file),
      read: file => files.get(file), write: (file, text) => files.set(file, text), remove: file => files.delete(file), chmod: () => {}, log: () => {} } };
  };
  const custom = `#!/bin/sh\n# note: the generated one says ${HOOK_MARKER}\nnpm test\n`;
  for (const action of ['install', 'remove']) {
    const h = harness(custom);
    assert.throws(() => manageHook(action, h.options), /not generated by Relayrace/);
    assert.equal(h.files.get(HOOK), custom);
  }
  for (const own of [hookScript({ node: 'n', cli: 'c' }), `#!/bin/sh\n${LEGACY_HOOK_MARKERS[0]}\nexec x\n`]) {
    const h = harness(own);
    assert.equal(manageHook('remove', h.options), 0);
    assert.equal(h.files.has(HOOK), false);
  }
});
